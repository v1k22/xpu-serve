#pragma once

#include <cstdlib>
#include <filesystem>
#include <optional>

namespace xs::test {

// Directory of a real Hugging Face model (e.g. google/gemma-4-E2B-it) for tests that need one; nullopt when unset.
inline std::optional<std::filesystem::path> model_dir() {
    const char* p = std::getenv("XS_TEST_MODEL_DIR");
    if (p == nullptr || *p == '\0') return std::nullopt;
    return std::filesystem::path(p);
}

// Directory of a LiquidAI/LFM3-1.7B checkpoint, for the tests of its tokenizer and chat template (neither is kept in
// this repository); nullopt when XS_LFM3_DIR is unset.
inline std::optional<std::filesystem::path> lfm3_dir() {
    const char* p = std::getenv("XS_LFM3_DIR");
    if (p == nullptr || *p == '\0') return std::nullopt;
    return std::filesystem::path(p);
}

// Directory of a Llama 3.x checkpoint (unsloth/Llama-3.2-1B-Instruct, or its tokenizer.json alone; not kept in this
// repository), for the parity of its tokenizer; nullopt when XS_LLAMA3_DIR is unset.
inline std::optional<std::filesystem::path> llama3_dir() {
    const char* p = std::getenv("XS_LLAMA3_DIR");
    if (p == nullptr || *p == '\0') return std::nullopt;
    return std::filesystem::path(p);
}

// Directory of a thinkingmachines/Inkling-2-Mini checkpoint, or of its tokenizer.json alone (not kept in this
// repository), for the parity of its tokenizer; nullopt when XS_INKLING2_DIR is unset.
inline std::optional<std::filesystem::path> inkling2_dir() {
    const char* p = std::getenv("XS_INKLING2_DIR");
    if (p == nullptr || *p == '\0') return std::nullopt;
    return std::filesystem::path(p);
}

// Directory of a Qwen/Qwen3-ASR-1.7B checkpoint, or of its slow tokenizer files alone (vocab.json, merges.txt,
// tokenizer_config.json: not kept in this repository), for the parity of a tokenizer built from them; nullopt when
// XS_QWEN3_ASR_DIR is unset.
inline std::optional<std::filesystem::path> qwen3_asr_dir() {
    const char* p = std::getenv("XS_QWEN3_ASR_DIR");
    if (p == nullptr || *p == '\0') return std::nullopt;
    return std::filesystem::path(p);
}

// Directory of generated reference fixtures (tests/fixtures/generated by default); nullopt when it does not exist.
inline std::optional<std::filesystem::path> fixtures_dir() {
    const char* p = std::getenv("XS_TEST_FIXTURES");
    std::filesystem::path dir = p != nullptr && *p != '\0' ? std::filesystem::path(p)
                                                            : std::filesystem::path(XS_SOURCE_DIR) / "tests/fixtures";
    if (!std::filesystem::exists(dir)) return std::nullopt;
    return dir;
}

}  // namespace xs::test
